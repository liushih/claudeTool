"""把 skills/ 渲染成 Claude / Cursor / Codex 的入口文件。"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

SKILLS = ["data-gen-core", "db-access", "adapter-bootstrap"]
GENERATED = "<!-- generated by hexin-tools v1; edit source, do not edit here -->\n"
BEGIN = "<!-- hexin-tools:begin -->"
END = "<!-- hexin-tools:end -->"


def _parse_skill(path: Path) -> tuple[dict, str]:
    text = path.read_text(encoding="utf-8")
    if text.startswith("---"):
        _, front, body = text.split("---", 2)
        return yaml.safe_load(front) or {}, body.lstrip("\n")
    return {}, text


def render(tool: str, name: str, body: str, description: str, tools_dir: Path) -> str:
    body = body.replace("<TOOLS_DIR>", Path(tools_dir).as_posix())
    if tool == "claude":
        return f"---\nname: {name}\ndescription: {description}\n---\n\n{GENERATED}{body}"
    if tool == "cursor":
        return (
            f"---\ndescription: {description}\nglobs: []\n"
            f"alwaysApply: false\n---\n\n{GENERATED}{body}"
        )
    return body


def _require_project(project_dir) -> Path:
    if not project_dir:
        raise ValueError("cursor / codex 需要 --project-dir")
    return Path(project_dir)


def _codex_block(tools_dir: Path) -> str:
    lines = [BEGIN, "## 数据工具", ""]
    for name in SKILLS:
        meta, _ = _parse_skill(tools_dir / "skills" / name / "SKILL.md")
        lines.append(f"- {name}: {meta.get('description', '')}")
    lines.append("")
    lines.append(f"详细规则：{Path(tools_dir).as_posix()}/skills")
    lines.append(END)
    return "\n".join(lines) + "\n"


def _upsert_block(path: Path, block: str) -> None:
    existing = path.read_text(encoding="utf-8") if path.exists() else ""
    existing = re.sub(rf"{re.escape(BEGIN)}.*?{re.escape(END)}\n?", "", existing, flags=re.S)
    prefix = existing.rstrip() + "\n\n" if existing.strip() else ""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text((prefix + block).rstrip() + "\n", encoding="utf-8")


def install(targets: list[str], scope: str, project_dir, tools_dir: Path, home: Path) -> list[Path]:
    tools_dir = Path(tools_dir)
    written: list[Path] = []

    for tool in targets:
        if tool == "claude":
            base = (Path(home) / ".claude" / "skills") if scope == "global" \
                else (_require_project(project_dir) / ".claude" / "skills")
            for name in SKILLS:
                meta, body = _parse_skill(tools_dir / "skills" / name / "SKILL.md")
                out = base / name / "SKILL.md"
                out.parent.mkdir(parents=True, exist_ok=True)
                out.write_text(
                    render("claude", name, body, meta.get("description", ""), tools_dir),
                    encoding="utf-8",
                )
                written.append(out)

        elif tool == "cursor":
            base = _require_project(project_dir) / ".cursor" / "rules"
            base.mkdir(parents=True, exist_ok=True)
            for name in SKILLS:
                meta, body = _parse_skill(tools_dir / "skills" / name / "SKILL.md")
                out = base / f"{name}.mdc"
                out.write_text(
                    render("cursor", name, body, meta.get("description", ""), tools_dir),
                    encoding="utf-8",
                )
                written.append(out)

        elif tool == "codex":
            out = _require_project(project_dir) / "AGENTS.md"
            _upsert_block(out, _codex_block(tools_dir))
            written.append(out)

        else:
            raise ValueError(f"未知工具 {tool}")

    return written


def remove(targets: list[str], scope: str, project_dir, home: Path) -> None:
    for tool in targets:
        if tool == "claude":
            base = (Path(home) / ".claude" / "skills") if scope == "global" \
                else (_require_project(project_dir) / ".claude" / "skills")
            for name in SKILLS:
                out = base / name / "SKILL.md"
                if out.exists():
                    out.unlink()
                if out.parent.exists() and not any(out.parent.iterdir()):
                    out.parent.rmdir()

        elif tool == "cursor":
            if not project_dir:
                continue
            base = _require_project(project_dir) / ".cursor" / "rules"
            for name in SKILLS:
                out = base / f"{name}.mdc"
                if out.exists():
                    out.unlink()

        elif tool == "codex":
            if not project_dir:
                continue
            out = _require_project(project_dir) / "AGENTS.md"
            if out.exists():
                text = out.read_text(encoding="utf-8")
                text = re.sub(rf"{re.escape(BEGIN)}.*?{re.escape(END)}\n?", "", text, flags=re.S)
                out.write_text(text.rstrip() + "\n", encoding="utf-8") if text.strip() else out.unlink()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="生成 Claude / Cursor / Codex 入口文件")
    parser.add_argument("--target", default="claude,cursor,codex")
    parser.add_argument("--scope", default="global", choices=["global", "project"])
    parser.add_argument("--project-dir")
    parser.add_argument("--tools-dir", default=str(Path(__file__).resolve().parents[1]))
    parser.add_argument("--home", default=str(Path.home()))
    parser.add_argument("--remove", action="store_true")
    args = parser.parse_args(argv)

    targets = [t.strip() for t in args.target.split(",") if t.strip()]
    try:
        if args.remove:
            remove(targets, args.scope, args.project_dir, Path(args.home))
            print("已移除生成文件")
            return 0

        for path in install(targets, args.scope, args.project_dir, Path(args.tools_dir), Path(args.home)):
            print(path)
    except ValueError as exc:
        print(exc, file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
